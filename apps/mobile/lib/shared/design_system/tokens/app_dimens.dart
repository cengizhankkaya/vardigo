/// Spacing and sizes from the case design tokens, in logical pixels.
abstract final class AppSpacing {
  static const double page = 20;
  static const double iconText = 4;
  static const double cardPhotoText = 12;
  static const double candidateCardGap = 10;
  static const double offerCardGap = 12;
}

abstract final class AppRadius {
  static const double card = 20;
  static const double squareButton = 12;
  static const double chip = 12;
  static const double cta = 10;
  static const double actionButton = 8;
  static const double checkbox = 6;
  static const double pill = 999;
}

abstract final class AppSizes {
  static const double avatar = 56;
  static const double onlineBadge = 24;
  static const double squareButton = 44;
  static const double checkbox = 20;
  static const double cta = 44;
  static const double actionButton = 36;

  /// Reference phone frame.
  static const double frameWidth = 390;
  static const double frameHeight = 844;
}
